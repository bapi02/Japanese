def reword_detail(d):
    if d is None: return None
    d = str(d)
    if d in DETAIL: return DETAIL[d]
    x = d.replace("STAFF", "스태프").replace("인건비", "인력").replace("운송비", "운반비").replace("시공", "설치")
    return re.sub(r"\s+", " ", x).strip()

def nice(v):
    if v <= 0: return 0
    step = 100000 if v >= 10_000_000 else 10000 if v >= 1_000_000 else 1000 if v >= 100_000 else 100 if v >= 10_000 else 10
    return int(round(v / step) * step)
def factor(key):
    h = int(hashlib.md5(key.encode()).hexdigest(), 16) % 1000
    return 1.03 + 0.05 * h / 999   # 1.03 ~ 1.08

