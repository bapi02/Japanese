/** 'YYYY-MM-DD' 두 날짜(포함) 사이의 모든 날짜를 반환. */
export function datesBetween(from, to) {
  const out = [];
  const d = new Date(from + 'T00:00:00Z');
  const end = new Date(to + 'T00:00:00Z');
  while (d <= end) {
    out.push(d.toISOString().slice(0, 10));
    d.setUTCDate(d.getUTCDate() + 1);
  }
  return out;
}

function inSeason(dateStr, season) {
  const md = dateStr.slice(5);
  // 연말연시처럼 연도를 넘는 구간 처리
  return season.from <= season.to
    ? md >= season.from && md <= season.to
    : md >= season.from || md <= season.to;
}

/**
 * 여행 구간(출발일~귀국일)에 걸친 공휴일 · 성수기를 찾는다.
 * @returns {{kr:{date:string,name:string}[], jp:{date:string,name:string}[], seasons:{name:string,weight:number}[]}}
 */
export function calendarContext(depDate, retDate) {
  const days = datesBetween(depDate, retDate);
  const kr = [];
  const jp = [];
  const seasonHits = new Map();
  for (const d of days) {
    if (KR_HOLIDAYS[d]) kr.push({ date: d, name: KR_HOLIDAYS[d] });
    if (JP_HOLIDAYS[d]) jp.push({ date: d, name: JP_HOLIDAYS[d] });
    for (const s of PEAK_SEASONS) {
      if (inSeason(d, s)) seasonHits.set(s.name, s.weight);
    }
  }
  return {
    kr,
    jp,
    seasons: [...seasonHits].map(([name, weight]) => ({ name, weight })),
  };
}
